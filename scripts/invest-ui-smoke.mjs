import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
import assert from 'node:assert/strict';
const html=readFileSync('public/index.html','utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1,'expected one inline script');
new Script(scripts[0][1],{filename:'runlu-invest-ui.js'});
assert.equal((html.match(/<\/html>/g)||[]).length,1,'expected one HTML ending');
for(const id of ['holdings','timeline','story','lessons','exportBackup','importBackup','backupFile','expectation','reason','saveMemory'])assert.ok(html.includes('id="'+id+'"'),'missing UI element '+id);
for(const feature of ['function renderStory','function renderLessons','function reviewMemory','Restore verification failed','Invalid or duplicate memory','READ-ONLY'])assert.ok(html.includes(feature),'missing '+feature);
assert.ok(!html.includes('/api/trade'),'UI must not call trade endpoints');
console.log('RUNLU INVEST static smoke checks passed');
